export interface AppErrorOptions {
  details?: Record<string, unknown>;
  requestId?: string;
  cause?: unknown;
}

/** 统一错误对象（业务层抛出，HTTP 层序列化为 §10 格式）。 */
export class AppError extends Error {
  readonly code: ErrorCode;
  readonly details: Record<string, unknown>;
  readonly requestId?: string;
  readonly httpStatus: number;

  constructor(code: ErrorCode, message: string, options: AppErrorOptions = {}) {
    super(message, options.cause !== undefined ? { cause: options.cause } : undefined);
    this.name = 'AppError';
    this.code = code;
    this.details = options.details ?? {};
    this.requestId = options.requestId;
    this.httpStatus = ERROR_HTTP_STATUS[code];
  }
}

/** 26 SPEC §10 规定的统一错误响应体。 */
export interface ErrorResponseBody {
  error: {
    code: ErrorCode;
    message: string;
    details: Record<string, unknown>;
    requestId: string;
  };
}

/** 把 AppError 序列化为 §10 统一错误响应体。 */
export function toErrorResponse(err: AppError, fallbackRequestId: string): ErrorResponseBody {
  return {
    error: {
      code: err.code,
      message: err.message,
      details: err.details,
      requestId: err.requestId ?? fallbackRequestId,
    },
  };
}
